def obtener_contexto(pictograma: str) -> str:
    """Retorna información base sobre el pictograma."""
    info = CONOCIMIENTO.get(pictograma.lower(), {})
    return info.get("dato", f"El {pictograma} es algo interesante.")

def obtener_respuesta_directa(pictograma: str, pregunta: str) -> str:
    """Busca una respuesta directa en las preguntas comunes."""
    info = CONOCIMIENTO.get(pictograma.lower(), {})
    preguntas = info.get("preguntas_comunes", {})
    
    pregunta_lower = pregunta.lower()
    
    # Buscar palabras clave en la pregunta
    for clave, respuesta in preguntas.items():
        if clave in pregunta_lower:
            return respuesta
    
    return None